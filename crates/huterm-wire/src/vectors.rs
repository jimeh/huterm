/// The request, result, and cancel vectors.
fn request_vectors() -> Vec<MessageVector> {
    let from_server = |name, message, bytes| MessageVector {
        name,
        from: Direction::ServerToClient,
        message,
        bytes,
    };
    let from_client = |name, message, bytes| MessageVector {
        name,
        from: Direction::ClientToServer,
        message,
        bytes,
    };
    let id = |id| RequestId::new(id).expect("vector identities start at 1");
    let mut vectors = Vec::new();
    for ((request, bytes), number) in
        every_request().into_iter().zip(REQUESTS).zip(1..)
    {
        vectors.push(from_client(
            "request",
            Message::Request(RequestMessage {
                id: id(number),
                request,
            }),
            bytes,
        ));
    }
    for ((outcome, bytes), number) in
        every_outcome().into_iter().zip(RESULTS).zip(1..)
    {
        vectors.push(from_server(
            "result",
            Message::Result(RequestResult {
                request: id(number),
                outcome,
            }),
            bytes,
        ));
    }
    vectors.push(from_client(
        "cancel",
        Message::Cancel(Cancel { request: id(7) }),
        CANCEL,
    ));
    vectors
}

